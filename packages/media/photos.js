/* ==========================================================================
   ECHO ECHO — CAFÉ AND DISH PHOTOGRAPHS

   Two different kinds of picture, kept apart on purpose:

   * CAFÉ photos are the owner's own photographs of each kiosk, taken on
     campus on 16 Sep 2026 (the GPS Map Camera originals stay out of Git).
     tools/cafe-photos.py crops them: the camera's map/address overlay and
     every bystander's face are cut out, nothing is redrawn, and EXIF (with
     the GPS position) is not carried over.

   * DISH photos are openly licensed stock pictures matched to the dish's
     NAME. They are not pictures of the café's own food, so every surface
     that shows one says so, and DISH_CREDITS carries the attribution the
     licence asks for. A photo the counter uploads for a dish (menu_item.
     photo_asset) is the real thing and always wins over these.

   Lookups are pure functions of the slug or the dish name: the same dish
   gets the same photo on every load, and nothing here is written anywhere.
   URLs resolve against this module, so they work unchanged in the source
   tree and in the content-hashed build folder.
   ========================================================================== */
const asset = (name) => new URL(`./${name}`, import.meta.url).href;

/* Keyed by vendor slug, which survives renames (032 kept 'tulips').
   `position` is the object-position that keeps the sign and counter in a
   16:9 frame cut from each crop. */
