/* What a café card or header needs to draw the photo, or null. `slot` is the
   frame's aspect ratio (width / height): a photo wider than its frame is
   cropped at the sides, so the browser needs a proportionally wider file,
   and `scale` says how much wider. */
export function cafePhoto(slug, slot = 16 / 9) {
  const c = CAFES[slug];
  if (!c) return null;
  const srcset = c.widths.map((w) => `${asset(`cafes/${c.file}-${w}.webp`)} ${w}w`).join(', ');
  return {
    srcset, type: 'image/webp',
    src: asset(`cafes/${c.file}-${c.fallback}.jpg`),
    width: c.width, height: c.height, position: c.position, alt: c.alt,
    scale: Math.max(1, (c.width / c.height) / slot),
  };
}

