/* A dish added later that is not listed above still gets a photo when its
   name says plainly what it is: [pattern, vegetarian photo, meat photo].
   A dish whose name has meat in it gets the meat photo or none, and every
   other dish only ever gets a vegetarian one. Anything less certain keeps
   the monogram: a wrong picture is worse than none. */
const MEAT = /\b(chicken|egg|keema|mutton|fish|ham|salami|prawn|seekh)\b/;
const BY_WORD = [
  [/\b(wrap|roll)\b/, 'wrap-veg', 'wrap-chicken-tandoori'],
  [/\bsandwich\b/, 'sandwich-veg', 'sandwich-chicken'],
  [/\bpasta\b/, 'pasta-red', 'pasta-chicken'],
  [/\b(maggi|noodles?)\b/, 'noodles-masala', 'noodles-chicken'],
  [/\bhot dog\b/, 'hotdog-veg', 'hotdog'],
  [/\bfries\b/, 'fries', null],
  [/\b(cold|iced) coffee\b/, 'cold-coffee', null],
  [/\bgreen tea\b/, 'green-tea', null],
  [/\b(chai|kulhad)\b/, 'masala-chai', null],
];

export function dishPhotoKey(name) {
  const n = norm(name);
  if (!n) return null;
  if (BY_NAME[n]) return BY_NAME[n];
  const hit = BY_WORD.find(([re]) => re.test(n));
  if (!hit) return null;
  return (MEAT.test(n) ? hit[2] : hit[1]) || null;
}

/* { src, alt, key } for a dish name, or null. */
export function dishPhoto(name) {
  const key = dishPhotoKey(name);
  if (!key || !DISH_PHOTOS[key]) return null;
  return { key, src: asset(`dishes/${key}.webp`), alt: DISH_PHOTOS[key].alt };
}

